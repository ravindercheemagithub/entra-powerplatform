    flags = json.loads((BASE / "app-preview-flags.json").read_text())
    properties = {
        "Author": "", "Name": APP_NAME, "Id": APP_ID, "FileID": APP_ID,
        "LocalConnectionReferences": "{}", "LocalDatabaseReferences": "", "LibraryDependencies": "[]",
        "AppPreviewFlagsMap": flags,
        "DocumentLayoutWidth": 1366, "DocumentLayoutHeight": 768, "DocumentLayoutOrientation": "landscape",
        "DocumentLayoutScaleToFit": True, "DocumentLayoutMaintainAspectRatio": True, "DocumentLayoutLockOrientation": False,
        "ShowStatusBar": False, "AppCopilotSchemaName": "", "OriginatingVersion": "1.349",
        "DocumentAppType": "DesktopOrTablet", "DocumentType": "App", "AppCreationSource": "AppFromScratch",
        "AppDescription": "Entra ID self-service: register applications, expose APIs, app roles, role assignments, enterprise apps and security groups, with manager and Entra ID team approval.",
        "ManualOfflineProfileId": "", "DefaultConnectedDataSourceMaxGetRowsCount": 2000,
        "ContainsThirdPartyPcfControls": False, "ParserErrorCount": 0, "BindingErrorCount": 0,
        "ConnectionString": "", "EnableInstrumentation": False, "ControlCount": {},
    }
