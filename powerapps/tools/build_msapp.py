def validate_schema():
    """Validate every Src/*.pa.yaml against Microsoft's published pa.yaml v3 schema."""
    try:
        import jsonschema
    except ImportError:
        print("jsonschema not installed: schema validation skipped")
        return
    schema = yaml.safe_load((BASE / "pa.schema.yaml").read_text())
    validator = jsonschema.Draft7Validator(schema)
    problems = 0
    for f in sorted((SRC / "Src").glob("*.pa.yaml")):
        doc = yaml.safe_load(f.read_text())
        for err in validator.iter_errors(doc):
            problems += 1
            print(f"  schema: {f.name}: {'/'.join(map(str, err.absolute_path))}: {err.message[:160]}")
    print(f"schema validation: {problems} problem(s) in {len(list((SRC / 'Src').glob('*.pa.yaml')))} files")
    if problems:
        sys.exit(1)


def pack():
    pac = os.environ.get("PAC") or shutil.which("pac")
    if not pac:
        print("pac not found: set PAC=/path/to/pac to pack the .msapp")
        return
    DIST.mkdir(exist_ok=True)
    out = DIST / f"{FILE_STEM}.msapp"
    subprocess.run([pac, "canvas", "pack", "--sources", str(SRC), "--msapp", str(out), "--layout", "SourceCode",
                    "--overwrite"], check=True)
    print(f"packed {out}")


if __name__ == "__main__":
    write_sources()
    write_msapr()
    validate_schema()
    pack()
